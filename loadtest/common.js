import { check } from 'k6';

// Refuse remote targets by default: load tests should run against local Compose
// or an explicitly opted-in short-lived test VM, never the free cloud tier.
export function baseUrl() {
  const url = __ENV.BASE_URL || 'http://localhost:8000';
  const local = /^(http:\/\/localhost|http:\/\/127\.0\.0\.1)(:\d+)?$/i.test(url);
  if (!local && __ENV.ALLOW_REMOTE_LOADTEST !== 'true') {
    throw new Error('Remote target refused. Use local Compose, or explicitly set ALLOW_REMOTE_LOADTEST=true for a short-lived test VM.');
  }
  return url;
}

export function authHeaders() {
  return {
    'Content-Type': 'application/json',
    ...( __ENV.AUTH_TOKEN ? { Authorization: `Bearer ${__ENV.AUTH_TOKEN}` } : {}),
  };
}

export function checks(response, expected = 200) {
  check(response, { [`status is ${expected}`]: (r) => r.status === expected });
}

export function report(data) {
  const date = new Date().toISOString().replace(/[:.]/g, '-');
  const scenario = __ENV.SCENARIO || 'scenario';
  const setup = {
    scenario,
    target: __ENV.BASE_URL || 'http://localhost:8000',
    endpoint: __ENV.ENDPOINT || '/health',
    vus: __ENV.VUS || '10',
    duration: __ENV.DURATION || '30s',
    machine: __ENV.MACHINE_SPECS || 'not recorded; fill in the host CPU/RAM/OS',
    cacheMode: __ENV.CACHE_MODE || 'not applicable',
    branch: __ENV.GIT_BRANCH || 'not recorded',
    commit: __ENV.GIT_COMMIT || 'not recorded',
  };
  const file = `loadtest/results/${date}-${scenario}`;
  const summary = { setup, metrics: data.metrics };
  const p = (metric, stat) => data.metrics?.[metric]?.values?.[stat] ?? 'n/a';
  const markdown = [
    `# ${scenario} load-test result`, '',
    `- Date (UTC): ${new Date().toISOString()}`,
    `- Target: \`${setup.target}${setup.endpoint}\``,
    `- Load: ${setup.vus} VUs for ${setup.duration}`,
    `- Machine: ${setup.machine}`,
    `- Cache mode: ${setup.cacheMode}`,
    `- Branch / commit: ${setup.branch} / ${setup.commit}`,
    '', '| Measurement | Value |', '|---|---:|',
    `| Requests | ${p('http_reqs', 'count')} |`,
    `| Throughput (requests/s) | ${p('http_reqs', 'rate')} |`,
    `| p95 response time (ms) | ${p('http_req_duration', 'p(95)')} |`,
    `| Error rate | ${p('http_req_failed', 'rate')} |`,
    `| Checks passed | ${p('checks', 'rate')} |`, '',
    '> Compare runs only when machine, scenario, dataset, cache state, and load settings match. This report is generated by `handleSummary`; it does not claim a before/after improvement by itself.', '',
  ].join('\n');
  return { [`${file}.json`]: JSON.stringify(summary, null, 2), [`${file}.md`]: markdown };
}
